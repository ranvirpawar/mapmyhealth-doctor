export const generateBpHistory = (baseS, baseD) => {
  const months = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
  return months.map((m, i) => ({
    month: m,
    systolic: Math.round(baseS + Math.sin(i * 0.7) * 8 + (Math.random() - 0.5) * 10),
    diastolic: Math.round(baseD + Math.sin(i * 0.7) * 5 + (Math.random() - 0.5) * 6),
  }));
};

export const generateSugarHistory = (baseFasting) => {
  const weeks = ["W1", "W2", "W3", "W4", "W5", "W6", "W7", "W8", "W9", "W10", "W11", "W12"];
  return weeks.map((w, i) => ({
    week: w,
    fasting: Math.round(baseFasting + Math.sin(i * 0.8) * 20 + (Math.random() - 0.5) * 15),
    postPrandial: Math.round(baseFasting * 1.35 + Math.sin(i * 0.8) * 25 + (Math.random() - 0.5) * 20),
  }));
};

export const generateWeightHistory = (baseWeight) => {
  const months = ["Jan", "Feb", "Mar", "Apr", "May", "Jun"];
  return months.map((m, i) => ({
    month: m,
    weight: parseFloat((baseWeight - i * 0.3 + (Math.random() - 0.5) * 1.2).toFixed(1)),
  }));
};

